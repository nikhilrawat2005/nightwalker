#!/usr/bin/env python3
"""
Professional Novel Processor for Nightwalker
Usage:
    python tools/make_chapters.py The_Skills_I_Dont_Use_Anymore.docx

Features:
- Automatically parses chapters from Word (.docx) or Text (.txt)
- Intelligently recognizes Chapter 0, 1, 2... and subtitles
- Preserves bold lines as section sub-headings
- Automatically detects scene breaks (*** or ---)
- Detects WIP status for ongoing chapters
- Automatically syncs to js/chapters.js and updates novel library metadata
"""
import sys, re, json, os

def process_novel(input_file=None):
    if not input_file:
        # Search for novel docx in project root
        candidates = [
            'The_Skills_I_Dont_Use_Anymore.docx',
            'The Skills I Don.docx',
            'novel.docx'
        ]
        for c in candidates:
            if os.path.exists(c):
                input_file = c
                break
        if not input_file:
            # Check any .docx in root
            for f in os.listdir('.'):
                if f.lower().endswith('.docx') and not f.startswith('~$'):
                    input_file = f
                    break

    if not input_file or not os.path.exists(input_file):
        print(f"Error: Could not find document file '{input_file}'. Place your .docx in the project root.")
        return False

    print(f"[*] Processing manuscript: {input_file}")

    lines = []
    if input_file.lower().endswith('.docx'):
        import docx, io, shutil, tempfile
        # Copy to temp file or memory buffer in case Word/OneDrive has a lock on the file
        temp_dir = tempfile.mkdtemp()
        temp_copy = os.path.join(temp_dir, 'manuscript.docx')
        try:
            shutil.copy2(input_file, temp_copy)
            doc = docx.Document(temp_copy)
        finally:
            if os.path.exists(temp_copy):
                os.remove(temp_copy)
            if os.path.exists(temp_dir):
                os.rmdir(temp_dir)

        for p in doc.paragraphs:
            t = p.text.strip()
            if not t:
                continue
            runs = [r for r in p.runs if r.text.strip()]
            bold = (bool(runs) and all(r.bold or (p.style.font and p.style.font.bold) for r in runs)) or p.style.name.lower().startswith('heading')
            lines.append((t, bold))
    else:
        with open(input_file, 'r', encoding='utf-8') as f:
            for raw in f:
                t = raw.strip()
                if not t:
                    continue
                if t.startswith('## '):
                    lines.append((t[3:].strip(), True))
                else:
                    lines.append((t, False))

    CH = re.compile(r'^(chapter|अध्याय)\s*[-–:]?\s*(\d+)\b\s*[-–:.]?\s*(.*)$', re.I)
    SB = re.compile(r'^(\*\s*){3,}$|^[-–—_]{3,}$|^[·•]\s*[·•]\s*[·•]$')

    chapters = []
    current_ch = None

    for t, is_bold in lines:
        m = CH.match(t)
        if m and len(t) < 80:
            ch_num = int(m.group(2))
            sub = m.group(3).strip()
            current_ch = {
                'n': ch_num,
                'label': f'Chapter {ch_num}',
                'title': f'Chapter {ch_num}',
                'sub': sub,
                'sample': False,
                'inProgress': False,
                'blocks': [],
                '_fresh': True
            }
            chapters.append(current_ch)
            continue

        if current_ch is None:
            # Title before chapter 0
            continue

        # If next line after Chapter N is a short subtitle line
        if current_ch['_fresh'] and not current_ch['sub'] and len(t) < 80 and not t.endswith(('.','।','?','!')):
            current_ch['sub'] = t
            current_ch['_fresh'] = False
            continue

        current_ch['_fresh'] = False

        if SB.match(t):
            current_ch['blocks'].append({'t': 'br'})
        elif is_bold and len(t) < 120:
            current_ch['blocks'].append({'t': 'h', 'x': t})
        else:
            current_ch['blocks'].append({'t': 'p', 'x': t})

    for c in chapters:
        c.pop('_fresh', None)
        if c['n'] == 0:
            c['label'] = 'Chapter 0'

    # Check WIP status on the last chapter
    if chapters:
        last = chapters[-1]
        p_blocks = [b['x'] for b in last['blocks'] if b['t'] == 'p']
        if not p_blocks or not re.search(r'[.।?!”"’…)]\s*$', p_blocks[-1]) or (last['blocks'] and last['blocks'][-1]['t'] == 'h'):
            last['inProgress'] = True

    # Output to js/chapters.js
    novel_title = "The Skills I Don’t Use Anymore"
    novel_blurb = "Ek kitab jo seekhne ke baad likhi gayi. Chapter by chapter, jaise tum likhte ho."

    out_data = {
        'title': novel_title,
        'blurb': novel_blurb,
        'chapters': chapters
    }

    js_code = '/* Generated by tools/make_chapters.py */\nwindow.NOVEL = ' + json.dumps(out_data, ensure_ascii=False, indent=1) + ';\n'
    
    script_dir = os.path.dirname(os.path.abspath(__file__))
    target_js = os.path.join(script_dir, '..', 'js', 'chapters.js')
    
    with open(target_js, 'w', encoding='utf-8') as f:
        f.write(js_code)

    # Also automatically update js/novels_data.js chapter index metadata
    target_data = os.path.join(script_dir, '..', 'js', 'novels_data.js')
    novels_catalog = [
        {
            "id": "skills",
            "title": novel_title,
            "genre": "Memoir · Coming of Age",
            "tagline": novel_blurb,
            "status": f"Ongoing ({len(chapters)} Chapters)",
            "badge": "In Progress" if any(c.get('inProgress') for c in chapters) else "Complete",
            "color": "#E8795A",
            "coverImg": "assets/photos/1000165039_jpg.webp",
            "coverDesc": "A personal memoir exploring silence, attention, heartbreak, and unlearning the habits you once built to survive.",
            "chaptersFile": "js/chapters.js",
            "chapters": [
                {
                    "n": c["n"],
                    "label": c["label"],
                    "title": c["title"],
                    "sub": c.get("sub", ""),
                    "sample": False
                }
                for c in chapters
            ]
        }
    ]

    with open(target_data, 'w', encoding='utf-8') as f:
        f.write('/* Multi-novel catalog and library data for Nightwalker */\nwindow.NOVELS = ' + json.dumps(novels_catalog, ensure_ascii=False, indent=2) + ';\n')

    print(f"[OK] Successfully parsed {len(chapters)} chapters:")
    for c in chapters:
        wip_tag = " (In Progress)" if c.get('inProgress') else ""
        print(f"   - {c['label']}: \"{c.get('sub', '')}\" ({len(c['blocks'])} blocks){wip_tag}")
    print(f"Updated: {os.path.normpath(target_js)}")
    print(f"Updated: {os.path.normpath(target_data)}")
    return True

if __name__ == '__main__':
    src = sys.argv[1] if len(sys.argv) > 1 else None
    process_novel(src)
