#!/usr/bin/env python3
"""Novel doc -> js/chapters.js
Usage:  python3 tools/make_chapters.py novel.docx   (Google Doc: File > Download > .docx)
        python3 tools/make_chapters.py novel.txt    (plain text; lines starting '## ' are sub-headings)
Rules (your formatting is the parser):
  'Chapter N'            starts a chapter; the next short line is its subtitle
  fully bold line        sub-heading (dot on the progress rail)
  ***  or  * * *  or ---  scene break
  last chapter           marked 'writing in progress' if it ends mid-sentence (or pass --wip N)
"""
import sys, re, json, os
args=[a for a in sys.argv[1:] if not a.startswith('--')]
wip=[int(a.split('=')[1]) for a in sys.argv[1:] if a.startswith('--wip=')]
outs=[a.split('=',1)[1] for a in sys.argv[1:] if a.startswith('--out=')]
if not args: sys.exit(__doc__)
src=args[0]; lines=[]  # (text, is_bold)
if src.lower().endswith('.docx'):
    import docx
    for p in docx.Document(src).paragraphs:
        t=p.text.strip()
        if not t: continue
        runs=[r for r in p.runs if r.text.strip()]
        bold=bool(runs) and all(r.bold or (p.style.font and p.style.font.bold) for r in runs) or p.style.name.lower().startswith('heading')
        lines.append((t,bold))
else:
    for raw in open(src,encoding='utf-8'):
        t=raw.strip()
        if not t: continue
        if t.startswith('## '): lines.append((t[3:].strip(),True))
        else: lines.append((t,False))
CH=re.compile(r'^(chapter|अध्याय)\s*[-–:]?\s*(\d+)\b\s*[-–:.]?\s*(.*)$',re.I)
SB=re.compile(r'^(\*\s*){3,}$|^[-–—_]{3,}$|^[·•]\s*[·•]\s*[·•]$')
chs=[];c=None
for t,b in lines:
    m=CH.match(t)
    if m and len(t)<80:
        c={'n':int(m.group(2)),'label':f'Chapter {int(m.group(2))}','title':'Chapter %d'%int(m.group(2)),'sub':m.group(3).strip(),'sample':False,'inProgress':False,'blocks':[],'_fresh':True}
        chs.append(c);continue
    if c is None: continue  # text before Chapter 0 (cover, notes) is skipped
    if c['_fresh'] and not c['sub'] and len(t)<70 and not t.endswith(('.','।','?','!')):
        c['sub']=t;c['_fresh']=False;continue
    c['_fresh']=False
    if SB.match(t): c['blocks'].append({'t':'br'})
    elif b and len(t)<120: c['blocks'].append({'t':'h','x':t})
    else: c['blocks'].append({'t':'p','x':t})
for c in chs:
    c.pop('_fresh')
    if c['n']==0: c['label']='Chapter 0'
if chs:
    last=chs[-1];lp=[b['x'] for b in last['blocks'] if b['t']=='p']
    if wip: 
        for c in chs: c['inProgress']=c['n'] in wip
    elif not lp or not re.search(r'[.।?!”"’…)]\s*$',lp[-1]) or (last['blocks'] and last['blocks'][-1]['t']=='h'): last['inProgress']=True
out='/* Generated by tools/make_chapters.py - re-run it after editing the doc. */\nwindow.NOVEL='+json.dumps({'title':'The Skills I Don’t Use Anymore','blurb':'Ek kitab jo seekhne ke baad likhi gayi. Chapter by chapter, jaise tum likhte ho.','chapters':chs},ensure_ascii=False,indent=1)+';\n'
dst=outs[0] if outs else os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','js','chapters.js')
open(dst,'w',encoding='utf-8').write(out)
print(f'{len(chs)} chapters ->',os.path.normpath(dst),[(c['n'],len(c['blocks']),'WIP' if c['inProgress'] else '') for c in chs])
